import yaml
from pathlib import Path


def format_condition(col_expr: str, values: list[str] | str) -> str:
    """Convert configuration values into a SQL comparison expression.

    Parameters
    ----------
    col_expr : str
        SQL expression compared against the values (e.g. a Jinja column ref).
    values : list of str or str
        One or more accepted values. A single value produces "=", multiple
        values produce "IN (...)".

    Returns
    -------
    str
        SQL comparison expression such as "col = 'x'" or "col IN ('x', 'y')".
    """
    if isinstance(values, str):
        return f"{col_expr} = '{values}'"
    if len(values) == 1:
        return f"{col_expr} = '{values[0]}'"
    quoted_vals = ", ".join(f"'{v}'" for v in values)
    return f"{col_expr} IN ({quoted_vals})"


def compile_macro(config_path: Path, output_path: Path) -> None:
    """Generate the map_channel dbt macro from the channel rules YAML.

    Reads config/channels.yaml (the single source of truth for channel
    grouping) and writes the ordered CASE expression to
    src/warehouse/macros/map_channel.sql so every layer shares the same
    mapping.

    Parameters
    ----------
    config_path : Path
        Path to config/channels.yaml.
    output_path : Path
        Path of the generated macro file; parent folders are created.

    Raises
    ------
    ValueError
        If a rule defines neither 'source' nor 'medium' conditions.
    """
    with config_path.open("r", encoding="utf-8") as f:
        config = yaml.safe_load(f)

    rules = config.get("rules", [])
    default_channel = config.get("default_channel", "unassigned")

    lines = [
        "-- Auto-generated by scripts/compile_channel_macro.py from config/channels.yaml",
        "{% macro map_channel(source_col, medium_col) -%}",
        "CASE",
    ]

    for rule in rules:
        channel = rule["channel"]
        conditions = []

        if "source" in rule:
            conditions.append(format_condition("{{ source_col }}", rule["source"]))
        if "medium" in rule:
            conditions.append(format_condition("{{ medium_col }}", rule["medium"]))

        if not conditions:
            raise ValueError(
                f"Rule for channel '{channel}' is missing both 'source' and 'medium' conditions."
            )

        when_clause = " AND ".join(conditions)
        lines.append(f"    WHEN {when_clause} THEN '{channel}'")

    lines.extend([
        f"    ELSE '{default_channel}'",
        "END",
        "{%- endmacro %}",
    ])

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Successfully compiled: {output_path}")


if __name__ == "__main__":
    ROOT_DIR = Path(__file__).resolve().parent.parent
    CONFIG_FILE = ROOT_DIR / "config" / "channels.yaml"
    OUTPUT_FILE = ROOT_DIR / "src" / "warehouse" / "macros" / "map_channel.sql"

    compile_macro(CONFIG_FILE, OUTPUT_FILE)